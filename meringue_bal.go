const Steps = `1. Freeze ice cream into a dome until firm (at least 2 hours, or overnight).
2. Bake or buy a cake base; set the frozen dome on it.
3. Whip meringue (one recipe: 4 egg whites, 1/4 tsp cream of tartar, 2/3 cup sugar).
4. Cover the ice cream and cake completely with meringue, sealing to the plate.
5. Brown with a kitchen torch or under a hot broiler (about 4 minutes in one recipe),
   keeping the meringue away from the oven roof and walls.
6. Rest 5-10 minutes, then slice. Leftovers keep wrapped in the freezer up to 7 days.`
